// The product-family version law's battery (night-cafe-mclaren-1).
// Real fixture trees on disk - mkdtemp, not mocks - because the law is
// a discovery contract: the walk, the family boundary, and the lock
// parity are all filesystem shape, and only real files pin that.

import { afterAll, describe, expect, it } from 'vitest';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
	auditVersionSurfaces,
	discoverManifests,
	isFamily,
	manifestPackage
} from '../version-family';

const roots: string[] = [];

afterAll(() => {
	for (const root of roots) rmSync(root, { recursive: true, force: true });
});

function makeRoot(): string {
	const root = mkdtempSync(join(tmpdir(), 'version-family-'));
	roots.push(root);
	return root;
}

function writeTree(root: string, files: Record<string, string>): void {
	for (const [rel, body] of Object.entries(files)) {
		const abs = join(root, rel);
		mkdirSync(join(abs, '..'), { recursive: true });
		writeFileSync(abs, body);
	}
}

function pkgJson(name: string, version: string): string {
	return JSON.stringify({ name, version, private: true });
}

const MANIFEST = (name: string, version: string): string =>
	`[package]\nname = "${name}"\nversion = "${version}"\nedition = "2021"\n`;

const DEPS = `

[dependencies]
some-dep = { version = "=0.6.0", default-features = false }
other-dep = "=1.2.3"
`;

const LOCK = (name: string, version: string, extra = ''): string =>
	`# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = "${name}"\nversion = "${version}"\n${extra}`;

describe('manifestPackage', () => {
	it('reads the [package] name and version', () => {
		expect(manifestPackage(MANIFEST('bmi-stellar-argon2id', '1.0.0'))).toEqual({
			name: 'bmi-stellar-argon2id',
			version: '1.0.0'
		});
	});

	it('never reads a dependency version line', () => {
		// The exact-pinned dependency versions stay invisible to the law.
		const parsed = manifestPackage(MANIFEST('bmi-stellar-argon2id', '1.0.0') + DEPS);
		expect(parsed).toEqual({ name: 'bmi-stellar-argon2id', version: '1.0.0' });
		expect(manifestPackage(DEPS.trim())).toBeNull();
	});

	it('returns null for a section that is not the package manifest', () => {
		// [package.metadata.x] is a different section; without a real
		// [package] the manifest is not a crate manifest.
		expect(manifestPackage('[package.metadata.x]\nkey = "v"\n')).toBeNull();
		expect(manifestPackage('[other]\nname = "x"\n')).toBeNull();
		expect(manifestPackage('')).toBeNull();
	});
});

describe('isFamily', () => {
	it('admits the prefix itself and hyphenated descendants', () => {
		expect(isFamily('bmi-stellar', 'bmi-stellar')).toBe(true);
		expect(isFamily('bmi-stellar-argon2id', 'bmi-stellar')).toBe(true);
		expect(isFamily('bmi-stellar-whatever-deep', 'bmi-stellar')).toBe(true);
	});

	it('keeps the hyphen as the boundary, never a prefix smear', () => {
		expect(isFamily('bmi-stellarish', 'bmi-stellar')).toBe(false);
		expect(isFamily('not-my-crate', 'bmi-stellar')).toBe(false);
		expect(isFamily('bmi', 'bmi-stellar')).toBe(false);
	});
});

describe('discoverManifests', () => {
	it('finds every Cargo.toml anywhere, skips build and dep and dot dirs', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '80.6.0'),
			'tests/bench/Cargo.toml': MANIFEST('bmi-stellar-bench', '80.6.0'),
			'deep/a/b/Cargo.toml': MANIFEST('bmi-stellar-deep', '80.6.0'),
			'node_modules/x/Cargo.toml': MANIFEST('foreign', '9.9.9'),
			'target/debug/Cargo.toml': MANIFEST('foreign', '9.9.9'),
			'.hidden/Cargo.toml': MANIFEST('foreign', '9.9.9')
		});
		const found = await discoverManifests(root);
		expect(found).toEqual([
			'deep/a/b/Cargo.toml',
			'engine/argon2id/Cargo.toml',
			'tests/bench/Cargo.toml'
		]);
	});

	it('returns an empty list on a tree without manifests', async () => {
		const root = makeRoot();
		writeTree(root, { 'package.json': pkgJson('bmi-stellar', '80.6.0') });
		expect(await discoverManifests(root)).toEqual([]);
	});
});

describe('auditVersionSurfaces', () => {
	it('holds vacuously on a tree with no manifests', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.6.0`\n'
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
		expect(audit.family).toEqual([]);
	});

	it('finds a family crate in a nested dir and accepts parity', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.6.0`\n',
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '80.6.0'),
			'engine/argon2id/Cargo.lock': LOCK('bmi-stellar-argon2id', '80.6.0')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
		expect(audit.family).toEqual([
			{ path: 'engine/argon2id/Cargo.toml', name: 'bmi-stellar-argon2id', version: '80.6.0' }
		]);
	});

	it('flags a family crate left behind at the old version', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '1.0.0')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toContain(
			'engine/argon2id/Cargo.toml: bmi-stellar-argon2id 1.0.0 != package.json 80.6.0'
		);
	});

	it('flags a stale committed lock beside an up-to-date manifest', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '80.6.0'),
			'engine/argon2id/Cargo.lock': LOCK('bmi-stellar-argon2id', '1.0.0')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toContain(
			'engine/argon2id/Cargo.toml: Cargo.lock 1.0.0 != package.json 80.6.0'
		);
	});

	it('notes an absent lock honestly instead of failing it', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.6.0`\n',
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '80.6.0')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
		expect(audit.notes).toContain(
			'engine/argon2id/Cargo.toml: no sibling Cargo.lock - cargo writes one on the next build'
		);
	});

	it('skips non-family crates as notes, never violations', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.6.0`\n',
			'vendored/other/Cargo.toml': MANIFEST('not-my-crate', '9.9.9')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
		expect(audit.nonFamily).toEqual(['vendored/other/Cargo.toml']);
	});

	it('keeps the hyphen boundary on discovered manifests too', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.6.0`\n',
			'smear/Cargo.toml': MANIFEST('bmi-stellarish', '9.9.9')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
		expect(audit.family).toEqual([]);
	});

	it('rides the pre-release suffix on every surface', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '100.0.0-dragon.1'),
			'DORMANT.md': 'Version: `100.0.0-dragon.1`\n',
			'engine/argon2id/Cargo.toml': MANIFEST('bmi-stellar-argon2id', '100.0.0-dragon.1'),
			'engine/argon2id/Cargo.lock': LOCK('bmi-stellar-argon2id', '100.0.0-dragon.1')
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([]);
	});

	it('reports one violation for an unreadable source of truth', async () => {
		const root = makeRoot();
		writeTree(root, { 'not-the-source.json': '{}' });
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toEqual([
			'package.json: unreadable - the version source of truth is missing'
		]);
	});

	it('still polices the DORMANT capsule alongside the family law', async () => {
		const root = makeRoot();
		writeTree(root, {
			'package.json': pkgJson('bmi-stellar', '80.6.0'),
			'DORMANT.md': 'Version: `80.5.9`\n'
		});
		const audit = await auditVersionSurfaces(root);
		expect(audit.violations).toContain('DORMANT.md capsule version 80.5.9 != package.json 80.6.0');
	});
});
