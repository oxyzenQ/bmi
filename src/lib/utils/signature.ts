export const BMI_STELLAR_SIGNATURE_HANDLE: string = (() => {
	const core = BMI_STELLAR_SIGNATURE_BUILDER;
	const open = core.lastIndexOf('(');
	return open !== -1 && core.endsWith(')') ? core.slice(open + 1, -1) : core;
})();

