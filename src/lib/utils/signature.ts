// --- Mask machinery (shared by the generator's mirror contract) ------

const SIG_MASK64 = (1n << 64n) - 1n;

/** Golden-ratio increment (splitmix64's additive constant). */
const SIG_GOLDEN = 0x9e3779b97f4a7c15n;

/**
 * One splitmix64 round. Written to mirror the generator byte-exactly;
 * changing one side requires changing both and re-running the tool.
 *
 * `BigInt.asUintN(64, x)` wraps `x` modulo 2^64, which for the
 * non-negative values in this mixer is exactly `x & SIG_MASK64` — the
 * generator's `(x) & MASK64` in Python. The wrap is spelled as a call
 * rather than a bitwise mask so the `+` result sits in call-argument
 * position: CodeQL's JS value model has no bigint, classifies a `+`
 * over TS-bigint operands as a string append, and reads a bitwise
 * operand fed by such a `+` as an implicit operand conversion. Every
 * computed value stays byte-identical to the generator.
 */
function sigSplitmix64Mix(z: bigint): bigint {
	const a = BigInt.asUintN(64, z + SIG_GOLDEN);
	const b = ((a ^ (a >> 30n)) * 0xbf58476d1ce4e5b9n) & SIG_MASK64;
	const c = ((b ^ (b >> 27n)) * 0x94d049bb133111ebn) & SIG_MASK64;
	return (c ^ (c >> 31n)) & SIG_MASK64;
}

/**
 * Mask stream for word `index`: mix(seed + (index + 1) * GOLDEN).
 * Index-addressable (no sequential state to mirror), deterministic,
 * and different per layer because the seeds differ. The wrap is
 * `BigInt.asUintN(64, ...)` for the same reason as in
 * `sigSplitmix64Mix` — value-identical to the generator's `& MASK64`.
 */
export function maskFor(seed: bigint, index: number): bigint {
	const step = BigInt(index + 1);
	return sigSplitmix64Mix(BigInt.asUintN(64, seed + SIG_GOLDEN * step));
}

/**
 * Unmask a layer's words into clear bytes (zero-padded words
 * truncated to `byteLen`, little-endian, exactly the generator's
 * chunking). Exported for the gate's independent recompute and the
 * test tamper simulation.
 */
export function unmaskLayer(words: readonly bigint[], seed: bigint, byteLen: number): Uint8Array {
	const out = new Uint8Array(words.length * 8);
	for (let i = 0; i < words.length; i++) {
		const clear = (words[i] ?? 0n) ^ maskFor(seed, i);
		for (let b = 0; b < 8; b++) {
			out[i * 8 + b] = Number((clear >> BigInt(8 * b)) & 0xffn);
		}
	}
	return out.slice(0, byteLen);
}

/** BLAKE3-256 over the clear bytes, lowercase hex (the D2 digest). */
export function blake3Hex(bytes: Uint8Array): string {
	let hex = '';
	for (const byte of blake3(bytes)) {
		hex += byte.toString(16).padStart(2, '0');
	}
	return hex;
}

// --- Identity binding -------------------------------------------------

/** Marker separating the manifest's brand prose from the owner identity. Plaintext is safe here: it carries no identity, and its bytes sit inside the manifest, bound by MANIFEST_FINGERPRINT. */
const MANIFEST_IDENTITY_MARKER = 'Official Build by ';

/** Year suffix the manifest carries after the identity. Generic text, same binding rationale as the marker. */
const MANIFEST_IDENTITY_YEAR = ' 2026';

/**
 * Extract the owner identity core from a materialized manifest:
 * everything after the marker, minus the trailing year. `null` means
 * the manifest no longer carries the marker/year shape - a tampering
 * signal, not a crash path.
 */
export function identityCore(manifest: string): string | null {
	const index = manifest.indexOf(MANIFEST_IDENTITY_MARKER);
	if (index === -1) return null;
	const tail = manifest.slice(index + MANIFEST_IDENTITY_MARKER.length);
	if (!tail.endsWith(MANIFEST_IDENTITY_YEAR)) return null;
	return tail.slice(0, tail.length - MANIFEST_IDENTITY_YEAR.length);
}

// --- Version-report surface -------------------------------------------

export type ProvenanceStatus = 'verified' | 'tampered';

/** Everything the -V report and the About row render from the layers. */
export interface ProvenanceView {
	/** Full manifest text for the `Signature:` line. */
	manifest: string;
	/** Authors text for the `Copyright:` line. */
	authors: string;
	/** `Depth-matrix:` line (fingerprint + status + layers). */
	depthLine: string;
	/** The two-fold verification verdict. */
	status: ProvenanceStatus;
}

/**
 * Materialize the provenance layers and verify them, in one pass per
 * layer (see the single-pass invariant above). Verification is
 * two-fold and both halves must hold for status=verified:
 *
 * 1. Fingerprint: the runtime BLAKE3 fold over the clear bytes equals
 *    the embedded D2 digest for BOTH layers. Catches any patched word.
 * 2. Binding: the identity core extracted from the manifest is a
 *    prefix of the authors string. Catches incoherent single-layer
 *    rebrands (the identity claims disagree).
 *
 * Tampered bytes may not decode as UTF-8; TextDecoder renders
 * replacement characters instead of throwing - the status line is the
 * honest signal, and a broken identity display next to `tampered` is
 * itself evidence.
 */
export function provenanceView(): ProvenanceView {
	const manifestBytes = unmaskLayer(MASKED_MANIFEST_WORDS, MANIFEST_SEED, MANIFEST_BYTE_LEN);
	const authorsBytes = unmaskLayer(MASKED_AUTHORS_WORDS, AUTHORS_SEED, AUTHORS_BYTE_LEN);
	// One unmask pass per layer; these exact bytes feed the display and
	// the folds - the single-pass invariant.
	const manifestFingerprint = blake3Hex(manifestBytes);
	const authorsFingerprint = blake3Hex(authorsBytes);
	const fingerprintsOk =
		manifestFingerprint === MANIFEST_FINGERPRINT && authorsFingerprint === AUTHORS_FINGERPRINT;

	const manifest = new TextDecoder('utf-8').decode(manifestBytes);
	const authors = new TextDecoder('utf-8').decode(authorsBytes);

	const core = identityCore(manifest);
	const bindingOk = core !== null && authors.startsWith(core);

	const status: ProvenanceStatus = fingerprintsOk && bindingOk ? 'verified' : 'tampered';
	const depthLine = `Depth-matrix: fp=${MANIFEST_FINGERPRINT.slice(0, 16)} status=${status} layers=d0:masked-words,d1:masked-words,d2:dual-fingerprint`;

	return { manifest, authors, depthLine, status };
}

// --- Public contract (kept stable across the signature generations) ---

const materialized = provenanceView();

