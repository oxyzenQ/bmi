// --- Mask machinery (shared by the generator's mirror contract) ------

const SIG_MASK64 = (1n << 64n) - 1n;

/**
 * Golden-ratio increment (splitmix64's additive constant). Written as a
 * `BigInt("0x…")` conversion rather than an n-suffixed hex literal:
 * CodeQL's JS value model cannot parse the latter (its literal analysis
 * is float-based) and would read this constant as `undefined`, flagging
 * every arithmetic use of it as an implicit operand conversion. The
 * runtime value is identical.
 */
const SIG_GOLDEN = BigInt('0x9e3779b97f4a7c15');

/**
 * One splitmix64 round. Written to mirror the generator byte-exactly;
 * changing one side requires changing both and re-running the tool.
 * Every value here is a non-negative bigint, so `& SIG_MASK64` is the
 * generator's `(x) & MASK64` in Python, and every computed value stays
 * byte-identical to it.
 */
function sigSplitmix64Mix(z: bigint): bigint {
	const a = (z + SIG_GOLDEN) & SIG_MASK64;
	const b = ((a ^ (a >> 30n)) * 0xbf58476d1ce4e5b9n) & SIG_MASK64;
	const c = ((b ^ (b >> 27n)) * 0x94d049bb133111ebn) & SIG_MASK64;
	return (c ^ (c >> 31n)) & SIG_MASK64;
}

/**
 * Mask stream for word `index`: mix(seed + (index + 1) * GOLDEN).
 * Index-addressable (no sequential state to mirror), deterministic,
 * and different per layer because the seeds differ.
 */
function maskFor(seed: bigint, index: number): bigint {
	const step = BigInt(index + 1);
	return sigSplitmix64Mix((seed + SIG_GOLDEN * step) & SIG_MASK64);
}

/**
 * Unmask a layer's words into clear bytes (zero-padded words
 * truncated to `byteLen`, little-endian, exactly the generator's
 * chunking). Exported for the gate's independent recompute and the
 * test tamper simulation.
 */
export function unmaskLayer(words: readonly bigint[], seed: bigint, byteLen: number): Uint8Array {
	const out = new Uint8Array(words.length * 8);
	for (let i = 0; i < words.length; i++) {
		const clear = (words[i] ?? 0n) ^ maskFor(seed, i);
		for (let b = 0; b < 8; b++) {
			out[i * 8 + b] = Number((clear >> BigInt(8 * b)) & 0xffn);
		}
	}
	return out.slice(0, byteLen);
}

/** Decode a lowercase hex string to bytes (the inverse of bytesToHex). */
function hexToBytes(hex: string): Uint8Array {
	const out = new Uint8Array(hex.length / 2);
	for (let i = 0; i < out.length; i++) {
		out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
	}
	return out;
}

/** BLAKE3-256 over the clear bytes, lowercase hex (the D2 digest). */
export function blake3Hex(bytes: Uint8Array): string {
	return bytesToHex(blake3(bytes));
}

// --- D3: Ed25519 verification (RFC 8032, no extra dependency) ---------
//
// The runtime third layer. Deliberately self-contained over BigInt
// arithmetic (extended homogeneous coordinates) instead of pulling
// @noble/curves: the app keeps its zero-curve dependency footprint,
// the gate re-runs the exact law the module ships, and the Python
// reference in scripts/release/generate-provenance-words.py plus
// `openssl pkeyutl -verify` cross-check it from two other languages
// (the RFC 8032 test vector below pins correctness in the tests).
// Verifying ONE signature per runtime is the whole workload, so the
// slow bigint form is a feature: nothing clever to get wrong.

/** 2^255 - 19, the Edwards curve field prime. */
const ED_P = (1n << 255n) - 19n;

/** The group order (8 * L is the full cofactor order). */
const ED_L = 2n ** 252n + 27742317777372353535851937790883648493n;

/** d = -121665/121666 mod p, the curve constant. */
const ED_D = (-121665n * modInverse(121666n, ED_P)) % ED_P;

/** Precomputed inverts for point decompression (see edRecoverX). */
function modInverse(value: bigint, modulus: bigint): bigint {
	// Fermat little theorem: a^(p-2) mod p for the prime field. Every
	// input here is non-zero by construction (RFC 8032 point shapes).
	let result = 1n;
	let base = ((value % modulus) + modulus) % modulus;
	let exponent = modulus - 2n;
	while (exponent > 0n) {
		if (exponent & 1n) result = (result * base) % modulus;
		base = (base * base) % modulus;
		exponent >>= 1n;
	}
	return result;
}

/** The 2^((p-1)/4) square-root helper for decompression. */
const ED_SQRT_M1 = modPow(2n, (ED_P - 1n) / 4n, ED_P);

function modPow(base: bigint, exponent: bigint, modulus: bigint): bigint {
	let result = 1n;
	let b = ((base % modulus) + modulus) % modulus;
	let e = exponent;
	while (e > 0n) {
		if (e & 1n) result = (result * b) % modulus;
		b = (b * b) % modulus;
		e >>= 1n;
	}
	return result;
}

/** A point in extended homogeneous coordinates (X:Y:Z:T), Z != 0. */
type EdPoint = { x: bigint; y: bigint; z: bigint; t: bigint };

/** The neutral element (0, 1) as (0:1:1:0). */
const ED_IDENTITY: EdPoint = { x: 0n, y: 1n, z: 1n, t: 0n };

/**
 * The standard base point derived, not hardcoded: B is the point with
 * y = 4/5 and the even x, computed once at module load (same law as
 * the Python reference).
 */
const ED_BASE: EdPoint = (() => {
	const y = (4n * modInverse(5n, ED_P)) % ED_P;
	const x = edRecoverX(y, false);
	return { x, y, z: 1n, t: (x * y) % ED_P };
})();

/** Recover the x coordinate from y (and its parity bit) on the curve. */
function edRecoverX(y: bigint, sign: boolean): bigint {
	if (y >= ED_P) throw new Error('point coordinate out of field');
	const xx = ((y * y - 1n) * modInverse(ED_D * y * y + 1n, ED_P)) % ED_P;
	let x = modPow(xx, (ED_P + 3n) / 8n, ED_P);
	if ((x * x - xx) % ED_P !== 0n) x = (x * ED_SQRT_M1) % ED_P;
	if ((x * x - xx) % ED_P !== 0n) throw new Error('not a curve point');
	if (x % 2n !== 0n) x = ED_P - x;
	if (sign && x % 2n === 0n) x = ED_P - x;
	if (!sign && x % 2n !== 0n) x = ED_P - x;
	return x;
}

/** Point addition in extended coordinates (his Complete formulas). */
function edAdd(p: EdPoint, q: EdPoint): EdPoint {
	const a = ((p.y - p.x) * (q.y - q.x)) % ED_P;
	const b = ((p.y + p.x) * (q.y + q.x)) % ED_P;
	const c = (2n * p.t * q.t * ED_D) % ED_P;
	const dd = (2n * p.z * q.z) % ED_P;
	const e = b - a;
	const f = dd - c;
	const g = dd + c;
	const h = b + a;
	return { x: (e * f) % ED_P, y: (g * h) % ED_P, z: (f * g) % ED_P, t: (e * h) % ED_P };
}

/** Scalar multiplication, double-and-add over the bigint scalar. */
function edMul(point: EdPoint, scalar: bigint): EdPoint {
	let result = ED_IDENTITY;
	let addend = point;
	while (scalar > 0n) {
		if (scalar & 1n) result = edAdd(result, addend);
		addend = edAdd(addend, addend);
		scalar >>= 1n;
	}
	return result;
}

/** Decode a 32-byte compressed point, verifying it lies on the curve. */
function edDecode(raw: Uint8Array): EdPoint {
	if (raw.length !== 32) throw new Error('point must be 32 bytes');
	let value = 0n;
	for (let i = 31; i >= 0; i--) value = (value << 8n) | BigInt(raw[i] ?? 0);
	// Parentheses are load-bearing here: `&` binds looser than `===` in
	// JS, so the unparenthesised form would mix BigInt with a boolean
	// and throw on every decode.
	const sign = ((value >> 255n) & 1n) === 1n;
	const y = value & ((1n << 255n) - 1n);
	if (y >= ED_P) throw new Error('non-canonical y coordinate');
	const x = edRecoverX(y, sign);
	// The curve equation itself: -x^2 + y^2 - 1 - d*x^2*y^2 = 0 mod p.
	// A y whose recovered x passes the square-root path still has to
	// satisfy this, or the bytes were never a point at all.
	if ((-x * x + y * y - 1n - ED_D * x * x * y * y) % ED_P !== 0n) {
		throw new Error('not a curve point');
	}
	return { x, y, z: 1n, t: (x * y) % ED_P };
}

/** True when two extended points are the same affine point. */
function edEqual(p: EdPoint, q: EdPoint): boolean {
	return (p.x * q.z - q.x * p.z) % ED_P === 0n && (p.y * q.z - q.y * p.z) % ED_P === 0n;
}

/** Encode a point to the 32-byte compressed form (little-endian y, x parity in the top bit). */
function edEncode(point: EdPoint): Uint8Array {
	const zInv = modInverse(point.z, ED_P);
	const x = (point.x * zInv) % ED_P;
	const y = (point.y * zInv) % ED_P;
	const out = new Uint8Array(32);
	for (let i = 0; i < 32; i++) out[i] = Number((y >> BigInt(8 * i)) & 0xffn);
	if (x % 2n === 1n) out[31] |= 0x80;
	return out;
}

/**
 * Ed25519 verification (RFC 8032 section 5.1.7), strict form: the
 * scalar s must be canonical (s < L) and both points must decompress
 * cleanly, so malleable or non-canonical forgeries fail closed.
 */
export function ed25519Verify(
	publicKey: Uint8Array,
	message: Uint8Array,
	signature: Uint8Array
): boolean {
	if (publicKey.length !== 32 || signature.length !== 64) return false;
	let aPoint: EdPoint;
	let rPoint: EdPoint;
	try {
		aPoint = edDecode(publicKey);
		rPoint = edDecode(signature.slice(0, 32));
	} catch {
		return false;
	}
	const scalarS = bytesToBigInt(signature.slice(32));
	if (scalarS >= ED_L) return false;
	const k = bytesToBigInt(sha512(concat(signature.slice(0, 32), publicKey, message))) % ED_L;
	return edEqual(edAdd(rPoint, edMul(aPoint, k)), edMul(ED_BASE, scalarS));
}

function bytesToBigInt(bytes: Uint8Array): bigint {
	let value = 0n;
	for (let i = bytes.length - 1; i >= 0; i--) value = (value << 8n) | BigInt(bytes[i] ?? 0);
	return value;
}

function concat(...parts: Uint8Array[]): Uint8Array {
	const total = parts.reduce((sum, part) => sum + part.length, 0);
	const out = new Uint8Array(total);
	let offset = 0;
	for (const part of parts) {
		out.set(part, offset);
		offset += part.length;
	}
	return out;
}

/**
 * The D3 message: u32le length + bytes, for the domain and each layer.
 * Every part is length-prefixed, so no boundary can be read two ways.
 * Mirrored byte-exactly by the generator's signable_payload.
 */
export function signablePayload(manifestBytes: Uint8Array, authorsBytes: Uint8Array): Uint8Array {
	const frame = (part: Uint8Array): Uint8Array => {
		const out = new Uint8Array(4 + part.length);
		new DataView(out.buffer).setUint32(0, part.length, true);
		out.set(part, 4);
		return out;
	};
	return concat(
		frame(new TextEncoder().encode(D3_DOMAIN)),
		frame(manifestBytes),
		frame(authorsBytes)
	);
}

// --- Identity binding -------------------------------------------------

/** Marker separating the manifest's brand prose from the owner identity. Plaintext is safe here: it carries no identity, and its bytes sit inside the manifest, bound by MANIFEST_FINGERPRINT. */
const MANIFEST_IDENTITY_MARKER = 'Official Build by ';

/** Year suffix the manifest carries after the identity. Generic text, same binding rationale as the marker. */
const MANIFEST_IDENTITY_YEAR = ' 2026';

/**
 * Extract the owner identity core from a materialized manifest:
 * everything after the marker, minus the trailing year. `null` means
 * the manifest no longer carries the marker/year shape - a tampering
 * signal, not a crash path.
 */
export function identityCore(manifest: string): string | null {
	const index = manifest.indexOf(MANIFEST_IDENTITY_MARKER);
	if (index === -1) return null;
	const tail = manifest.slice(index + MANIFEST_IDENTITY_MARKER.length);
	if (!tail.endsWith(MANIFEST_IDENTITY_YEAR)) return null;
	return tail.slice(0, tail.length - MANIFEST_IDENTITY_YEAR.length);
}

// --- Version-report surface -------------------------------------------

export type ProvenanceStatus = 'verified' | 'unsigned' | 'tampered';

/** Everything the -V report and the About row render from the layers. */
export interface ProvenanceView {
	/** Full manifest text for the `Signature:` line. */
	manifest: string;
	/** Authors text for the `Copyright:` line. */
	authors: string;
	/** `Depth-matrix:` line (fingerprint + status + layers). */
	depthLine: string;
	/** The two-fold verification verdict. */
	status: ProvenanceStatus;
}

/**
 * Materialize the provenance layers and verify them, in one pass per
 * layer (see the single-pass invariant above). Verification is
 * three-fold and every leg must hold for status=verified:
 *
 * 1. Fingerprint: the runtime BLAKE3 fold over the clear bytes equals
 *    the embedded D2 digest for BOTH layers. Catches any patched word.
 * 2. Binding: the identity core extracted from the manifest is a
 *    prefix of the authors string. Catches incoherent single-layer
 *    rebrands (the identity claims disagree).
 * 3. Publisher: the D3 Ed25519 signature over the framed clear bytes
 *    verifies under OWNER_PUBLIC_KEY. Catches the minted-matrix
 *    forgery (a thief re-running the generator self-consistently).
 *
 * An empty OWNER_SIGNATURE is the known unsigned state (identity or
 * key rotation pending): status=unsigned, distinct from tampered.
 *
 * Tampered bytes may not decode as UTF-8; TextDecoder renders
 * replacement characters instead of throwing - the status line is the
 * honest signal, and a broken identity display next to `tampered` is
 * itself evidence.
 */
export function provenanceView(): ProvenanceView {
	const manifestBytes = unmaskLayer(MASKED_MANIFEST_WORDS, MANIFEST_SEED, MANIFEST_BYTE_LEN);
	const authorsBytes = unmaskLayer(MASKED_AUTHORS_WORDS, AUTHORS_SEED, AUTHORS_BYTE_LEN);
	// One unmask pass per layer; these exact bytes feed the display, the
	// folds, and the D3 message - the single-pass invariant.
	const manifestFingerprint = blake3Hex(manifestBytes);
	const authorsFingerprint = blake3Hex(authorsBytes);
	const fingerprintsOk =
		manifestFingerprint === MANIFEST_FINGERPRINT && authorsFingerprint === AUTHORS_FINGERPRINT;

	const manifest = new TextDecoder('utf-8').decode(manifestBytes);
	const authors = new TextDecoder('utf-8').decode(authorsBytes);

	const core = identityCore(manifest);
	const bindingOk = core !== null && authors.startsWith(core);

	// The empty-signature state is compared through a widening read so
	// the literal type of the committed constant does not narrow this
	// into a no-comparison (the generator can legitimately emit '').
	const unsigned: boolean = (OWNER_SIGNATURE as string) === '';
	const publisherOk =
		!unsigned &&
		ed25519Verify(
			hexToBytes(OWNER_PUBLIC_KEY),
			signablePayload(manifestBytes, authorsBytes),
			hexToBytes(OWNER_SIGNATURE)
		);

	const status: ProvenanceStatus = unsigned
		? 'unsigned'
		: fingerprintsOk && bindingOk && publisherOk
			? 'verified'
			: 'tampered';
	const depthLine = `Depth-matrix: fp=${MANIFEST_FINGERPRINT.slice(0, 16)} status=${status} layers=d0:masked-words,d1:masked-words,d2:dual-fingerprint,d3:ed25519-publisher`;

	return { manifest, authors, depthLine, status };
}

