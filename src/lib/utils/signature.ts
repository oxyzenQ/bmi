/**
 * The provenance depth matrix - the embedded, masked build signature
 * (night-signature-1; night-signature-advanced-2 supersedes its draft,
 * mirroring the cosmostrix scheme).
 *
 * The ownership claim is embedded in MASKED form and materializes to
 * plaintext only at runtime, on the -V/--version surface (build.sh)
 * and the About Depth-matrix row. The owner's threat model: a thief
 * can grep the tree or the built bundle with strings(1), rg, or a
 * custom scanner, find any plaintext wording, and patch it out. Here
 * the mark is present only as opaque 64-bit BigInt words:
 *
 *   D0  MASKED_MANIFEST_WORDS - the full Signature-line manifest,
 *       chunked little-endian and XOR-masked with a splitmix64 stream
 *       keyed by MANIFEST_SEED. At rest: opaque integers in source and
 *       in the bundle - no printable run of four or more bytes exists
 *       (pinned mechanically by the gate and the tests).
 *
 *   D1  MASKED_AUTHORS_WORDS - the Copyright-line authors string,
 *       masked the same way under the independent AUTHORS_SEED. Two
 *       independent encodings of the same identity: patching one
 *       still leaves the other reconstructing the owner.
 *
 *   D2  MANIFEST_FINGERPRINT / AUTHORS_FINGERPRINT - BLAKE3-256
 *       digests over the CLEAR bytes, generated by
 *       scripts/release/generate-provenance-words.py (the committed
 *       truth source, which carries the identity in plaintext by
 *       design, the same way TRADEMARK.md does) and cross-checked
 *       against the canonical b3sum CLI. Recomputed at runtime;
 *       -V and the About row report status=verified or status=tampered.
 *
 * # The single-pass invariant (load-bearing)
 *
 * provenanceView() performs ONE unmask pass per layer and feeds the
 * SAME clear bytes to both the display and the BLAKE3 fold - whatever
 * the report shows is exactly the bytes the digests cover. Display
 * and integrity can never drift apart.
 *
 * # Identity binding between the layers
 *
 * The manifest carries "Official Build by <identity> <year>"; the
 * authors string starts with the same identity core. Patching one
 * layer alone breaks the binding; the Depth-matrix line flips to
 * status=tampered.
 *
 * # Threat model (honest limits)
 *
 * Provenance marking and tamper evidence, not DRM, and no resistance
 * to memory forensics: once materialized, the plaintext lives in
 * process memory. The defense targets the lazy grep-and-strip rebrand
 * (the owner's stated threat): the artifact carries no greppable
 * mark, so a thief cannot find what to remove, and a source rebrand
 * that rewrites the visible branding still ships constants it does
 * not recognize - their build keeps materializing the original owner.
 * A determined attacker who fully understands this module can
 * regenerate everything; the legal layer (AGPL-3.0-only,
 * TRADEMARK.md) is the backstop. The legitimate plaintext carriers
 * are the generator (truth source), the test oracles (never bundled),
 * and TRADEMARK.md.
 */

